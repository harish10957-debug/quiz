/* =========================================
   GAME VARIABLES
========================================= */

let currentLevel = 0;
let currentQuestion = 0;
let score = 0;

let timer;
let timeLeft = 15;


/* =========================================
   START QUIZ
========================================= */

function startQuiz(level) {

    currentLevel = level;

    currentQuestion = 0;

    score = 0;

    document.getElementById("levelScreen").style.display = "none";

    document.getElementById("resultScreen").style.display = "none";

    document.getElementById("quizScreen").style.display = "block";


    document.getElementById("levelBadge").textContent =
        "LEVEL " +
        String(level + 1).padStart(2, "0");


    showQuestion();
}


/* =========================================
   DISPLAY QUESTION
========================================= */

function showQuestion() {

    clearInterval(timer);


    const questionData =
        quizData[currentLevel][currentQuestion];


    document.getElementById("questionNumber").textContent =
        "QUESTION " +
        (currentQuestion + 1) +
        " / 10";


    document.getElementById("question").textContent =
        questionData.q;


    /* Progress */

    const progress =
        (currentQuestion / 10) * 100;

    document.getElementById("progress").style.width =
        progress + "%";


    /* Options */

    const optionsContainer =
        document.getElementById("options");

    optionsContainer.innerHTML = "";


    questionData.options.forEach(
        (option, index) => {

            const button =
                document.createElement("button");

            button.className = "option";

            button.textContent = option;


            button.onclick = function () {

                selectAnswer(
                    index,
                    button
                );

            };


            optionsContainer.appendChild(button);
        }
    );


    startTimer();
}


/* =========================================
   TIMER
========================================= */

function startTimer() {

    timeLeft = 15;

    document.getElementById("time").textContent =
        timeLeft;


    timer = setInterval(() => {

        timeLeft--;

        document.getElementById("time").textContent =
            timeLeft;


        if (timeLeft <= 0) {

            clearInterval(timer);

            disableOptions();

            setTimeout(
                nextQuestion,
                700
            );
        }

    }, 1000);
}


/* =========================================
   SELECT ANSWER
========================================= */

function selectAnswer(
    selected,
    button
) {

    clearInterval(timer);


    const correct =
        quizData[currentLevel][currentQuestion].answer;


    disableOptions();


    if (selected === correct) {

        button.classList.add("correct");

        score++;

    } else {

        button.classList.add("wrong");


        const buttons =
            document.querySelectorAll(".option");


        buttons[correct].classList.add(
            "correct"
        );
    }


    setTimeout(
        nextQuestion,
        900
    );
}


/* =========================================
   DISABLE OPTIONS
========================================= */

function disableOptions() {

    document
        .querySelectorAll(".option")
        .forEach(button => {

            button.disabled = true;

        });
}


/* =========================================
   NEXT QUESTION
========================================= */

function nextQuestion() {

    currentQuestion++;


    if (currentQuestion >= 10) {

        showResult();

    } else {

        showQuestion();
    }
}


/* =========================================
   SHOW RESULT
========================================= */

function showResult() {

    clearInterval(timer);


    document.getElementById("quizScreen").style.display =
        "none";

    document.getElementById("resultScreen").style.display =
        "block";


    document.getElementById("finalScore").textContent =
        score;


    let message;


    if (score === 10) {

        message =
            "🔥 PERFECT! You are a true Tech Legend!";

    } else if (score >= 8) {

        message =
            "🚀 Excellent! Your technology skills are powerful!";

    } else if (score >= 6) {

        message =
            "⚡ Great work! Keep upgrading your knowledge!";

    } else if (score >= 4) {

        message =
            "💻 Nice attempt! Keep learning and try again!";

    } else {

        message =
            "🧠 Keep learning and challenge yourself again!";
    }


    document.getElementById("resultMessage").textContent =
        message;
}



function goHome() {

    clearInterval(timer);


    document.getElementById("resultScreen").style.display =
        "none";

    document.getElementById("quizScreen").style.display =
        "none";

    document.getElementById("levelScreen").style.display =
        "block";
}

